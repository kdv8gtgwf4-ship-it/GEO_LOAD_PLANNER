# -*- coding: utf-8 -*-
"""Run before building the .exe. Finds the company logo (logo.png / logo.jpg / logo.webp ...)
in this folder and embeds it into logo_data.py, so the finished .exe always contains it
(no separate file needed). Needs Pillow:  pip install pillow"""
import base64
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXTS = (".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp")
OUT = os.path.join(HERE, "logo_data.py")


def main():
    from PIL import Image
    cands = sorted(n for n in os.listdir(HERE)
                   if n.lower().startswith("logo") and n.lower().endswith(EXTS))
    data = ""
    if not cands:
        print("WARNING: no logo file (logo.png, logo.jpg, ...) found - a text logo will be used.")
    else:
        path = os.path.join(HERE, cands[0])
        try:
            im = Image.open(path).convert("RGBA")
            if im.height > 360:  # plenty for the on-screen header and for the exported image
                r = 360 / im.height
                res = getattr(Image, "Resampling", Image)
                im = im.resize((max(1, int(im.width * r)), 360), res.LANCZOS)
            buf = io.BytesIO()
            im.save(buf, "PNG", optimize=True)
            data = base64.b64encode(buf.getvalue()).decode("ascii")
            print(f"Logo embedded from {cands[0]} ({im.width}x{im.height}).")
        except Exception as e:
            print(f"WARNING: could not read {cands[0]}: {e}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# generated by embed_logo.py - do not edit\n")
        f.write("LOGO_B64 = (\n")
        for i in range(0, len(data), 100):
            f.write(f'    "{data[i:i + 100]}"\n')
        if not data:
            f.write('    ""\n')
        f.write(")\n")


if __name__ == "__main__":
    try:
        main()
    except ImportError:
        print("Pillow is required: pip install pillow")
        sys.exit(1)
